#!/usr/bin/env node
// Copy the app's data contract into the API and regenerate its JSON schemas (OpenAPI
// components). Run whenever app/src/data/{types,interface}.ts change:  npm run api-types
// The API test `contract.test.ts` fails if the copies drift from the app.
import { execFileSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, "../../app/src/data");
const gen = join(here, "../api/src/generated");
const header = (f) => `// GENERATED by scripts/gen-api-types.mjs from app/src/data/${f} — do not edit.\n`;
writeFileSync(join(gen, "app-types.ts"), header("types.ts") + readFileSync(join(app, "types.ts"), "utf8"));
writeFileSync(
  join(gen, "app-interface.ts"),
  header("interface.ts") + readFileSync(join(app, "interface.ts"), "utf8").replace('from "./types";', 'from "./app-types.js";'),
);
const tmp = join(gen, "schemas.tmp.json");
execFileSync(join(here, "../node_modules/.bin/ts-json-schema-generator"), ["-p", join(gen, "app-types.ts"), "-t", "*", "--no-type-check", "-e", "export", "-o", tmp], { stdio: "inherit" });
const schema = JSON.parse(readFileSync(tmp, "utf8"));
rmSync(tmp);
const defs = JSON.parse(JSON.stringify(schema.definitions).replaceAll("#/definitions/", "#/components/schemas/"));
writeFileSync(
  join(gen, "schemas.ts"),
  header("types.ts") + `/** JSON Schemas of the app data types (OpenAPI components). */\nexport const SCHEMAS: Record<string, unknown> = ${JSON.stringify(defs, null, 2)};\n`,
);
console.log(`wrote api/src/generated/{app-types,app-interface,schemas}.ts (${Object.keys(defs).length} schemas)`);
