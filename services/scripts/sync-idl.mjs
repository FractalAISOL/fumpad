#!/usr/bin/env node
// Copy the Anchor-generated fumpad v0.7 IDL into the SDK as a TS module.
//   (cd ../contracts && anchor build -p fumpad) && npm run sync-idl
//   FUMPAD_IDL=/path/to/target/idl/fumpad.json npm run sync-idl     (e.g. a build of the contracts branch)
// The SDK's IDL-consistency tests then tell you which builders/decoders need updating.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = process.env.FUMPAD_IDL ?? join(here, "../../contracts/target/idl/fumpad.json");
if (!existsSync(src)) {
  console.error(`missing ${src} — run \`anchor build\` in contracts/ or set FUMPAD_IDL`);
  process.exit(1);
}
const body = readFileSync(src, "utf8").trim();
const idl = JSON.parse(body);
const sha = createHash("sha256").update(body).digest("hex");
const note = process.env.FUMPAD_IDL_SOURCE ?? "contracts/target/idl/fumpad.json";
const ts =
  `// GENERATED by scripts/sync-idl.mjs — do not edit.\n` +
  `// Source: ${note} (program ${idl.address}, ${idl.metadata?.name} ${idl.metadata?.version}; sha256 ${sha}).\n` +
  `import type { Idl } from "@anchor-lang/core";\n\n` +
  `/** Raw (snake_case) Anchor IDL of the fumpad v0.7 program. */\n` +
  `export const FUMPAD_IDL: Idl = ${body} as unknown as Idl;\n\n` +
  `export const FUMPAD_IDL_SHA256 = "${sha}";\n`;
const out = join(here, "../sdk/src/idl/fumpad.idl.ts");
writeFileSync(out, ts);
console.log(`generated sdk/src/idl/fumpad.idl.ts (${idl.instructions.length} instructions, sha256 ${sha.slice(0, 12)}…)`);
