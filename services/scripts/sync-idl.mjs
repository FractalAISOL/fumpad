#!/usr/bin/env node
// Copy the Anchor-generated IDLs + TS types from contracts/target into the SDK.
// Run after `anchor build` whenever the programs change:
//   (cd ../contracts && anchor build) && npm run sync-idl
// The SDK's IDL-consistency test then tells you which instruction builders need updating.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "../../contracts/target");
const out = join(here, "../sdk/src/v06/idl");
mkdirSync(out, { recursive: true });

const files = [
  ["idl/fumpad.json", "fumpad.json"],
  ["idl/fumpad_lp_locker.json", "fumpad_lp_locker.json"],
  ["types/fumpad.ts", "fumpad.ts"],
  ["types/fumpad_lp_locker.ts", "fumpad_lp_locker.ts"],
];
for (const [from, to] of files) {
  const src = join(target, from);
  if (!existsSync(src)) {
    console.error(`missing ${src} — run \`anchor build\` in contracts/ first`);
    process.exit(1);
  }
  copyFileSync(src, join(out, to));
  console.log(`synced ${from} -> sdk/src/idl/${to}`);
}

// JSON IDLs as TS modules: no JSON-import attributes needed in Node ESM or bundlers.
for (const [json, name, type] of [
  ["fumpad.json", "FUMPAD_IDL", "Fumpad"],
  ["fumpad_lp_locker.json", "LP_LOCKER_IDL", "FumpadLpLocker"],
]) {
  const body = readFileSync(join(out, json), "utf8");
  const mod = json.replace(".json", "");
  const ts =
    `// GENERATED by scripts/sync-idl.mjs from contracts/target/idl/${json} — do not edit.\n` +
    `import type { Idl } from "@anchor-lang/core";\n\n` +
    `/** Raw (snake_case) Anchor IDL; the camelCase \`${type}\` type in ./${mod}.ts is for \`Program<${type}>\`. */\n` +
    `export const ${name}: Idl = ${body.trim()} as unknown as Idl;\n`;
  writeFileSync(join(out, `${mod}.idl.ts`), ts);
  console.log(`generated sdk/src/idl/${mod}.idl.ts`);
}
