/**
 * Fumi web assets (anime kit, LOCKED for phase-2 agents). Turns the cut-outs the videos use
 * (marketing/animations/assets/mascot/<n>-<pose>.png, 3:4, transparent) into
 *   public/fumi/<pose>-360.webp and <pose>-720.webp   (alpha WebP, ~20–60 KB each)
 *   src/design/anime/manifest.ts                      (which poses have art; everything else falls back)
 * Drop a new pose PNG next to the others, run `npm run fumi`, and every <Fumi pose="…"> that was falling
 * back now shows the real art. Uses sharp (installed with next).
 *
 *   node scripts/fumi-assets.mjs
 */
import { readdirSync, mkdirSync, writeFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(app, "..", "marketing", "animations", "assets", "mascot");
const out = join(app, "public", "fumi");
mkdirSync(out, { recursive: true });

const WIDTHS = [360, 720];
const found = [];
for (const f of readdirSync(src).sort((a, b) => parseInt(a) - parseInt(b))) {
  const m = /^(\d+)-([a-z]+)\.png$/.exec(f);
  if (!m) continue;
  const pose = m[2];
  for (const w of WIDTHS) {
    const file = join(out, `${pose}-${w}.webp`);
    // Normalise to an exact 3:4 box (one source is 900×1200, the rest 896×1200).
    await sharp(join(src, f))
      .resize(w, Math.round((w * 4) / 3), { fit: "fill", kernel: "lanczos3" })
      .webp({ quality: 84, alphaQuality: 90, effort: 6, smartSubsample: true })
      .toFile(file);
    console.log(`${pose}-${w}.webp  ${(statSync(file).size / 1024).toFixed(0)} KB`);
  }
  found.push(pose);
}

writeFileSync(
  join(app, "src", "design", "anime", "manifest.ts"),
  `/* Generated by scripts/fumi-assets.mjs — do not edit. Poses with art in public/fumi/. */\n` +
    `export const FUMI_ART = ${JSON.stringify(found)} as const;\n` +
    `export const FUMI_WIDTHS = ${JSON.stringify(WIDTHS)} as const;\n`,
);
console.log(`manifest: ${found.length} poses`);
